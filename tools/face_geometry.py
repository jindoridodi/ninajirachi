"""Shared reference geometry for the desktop preview and firmware renderer."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEOMETRY = json.loads((ROOT / "shared/face_geometry.json").read_text())
OUTPUT = ROOT / "firmware/src/face/FaceGeometry.generated.h"


def sample_path(path):
    points = [tuple(path[0])]
    for segment in path[1:]:
        x0, y0 = points[-1]
        x1, y1, x2, y2, x3, y3 = segment
        for step in range(1, 25):
            t = step / 24
            u = 1 - t
            points.append((u**3*x0 + 3*u*u*t*x1 + 3*u*t*t*x2 + t**3*x3,
                           u**3*y0 + 3*u*u*t*y1 + 3*u*t*t*y2 + t**3*y3))
    return points


def display_geometry():
    g = GEOMETRY
    scale = g["displayWidth"] / g["sourceWidth"]
    ox, oy = (240 - g["displayWidth"]) / 2, (240 - g["sourceHeight"] * scale) / 2 + g["displayOffsetY"]
    def convert(path, rounded=True):
        points = [(ox + x * scale, oy + y * scale) for x, y in sample_path(path)]
        return [(round(x), round(y)) for x, y in points] if rounded else points
    return {
        "outline": convert(g["outline"]), "mouth": convert(g["mouth"], rounded=False),
        "outlineWidth": max(1, round(g["outlineWidth"] * scale)),
        "mouthWidth": round(g["mouthWidth"] * scale),
        "eyeRadius": round(g["eyeRadius"] * scale),
        "eyes": [(round(ox+x*scale), round(oy+y*scale), round(w*scale), round(h*scale))
                 for x, y, w, h in g["eyes"]],
    }


def render_header():
    g = display_geometry()
    rows = ["// Generated by tools/face_geometry.py; edit shared/face_geometry.json.",
            "#pragma once", "#include <stdint.h>", "", "namespace nina {", "",
            "struct FacePoint { int16_t x; int16_t y; };",
            "struct MouthPoint { float x; float y; };", ""]
    for key in ("outline", "mouth"):
        rows.append(f"static const {'FacePoint' if key == 'outline' else 'MouthPoint'} kFace{key.title()}[] = {{")
        rows.extend((f"    {{{x}, {y}}}," if key == "outline" else
                     f"    {{{x:.6f}f, {y:.6f}f}},") for x, y in g[key])
        rows.append("};")
    rows.append("static const int16_t kFaceEyes[2][4] = {")
    rows.extend("    {" + ", ".join(map(str, eye)) + "}," for eye in g["eyes"])
    rows.append("};")
    for key in ("outlineWidth", "mouthWidth", "eyeRadius"):
        rows.append(f"constexpr int16_t kFace{key[0].upper()+key[1:]} = {g[key]};")
    rows.extend(["", "}  // namespace nina", ""])
    return "\n".join(rows)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_header()
    if args.check:
        raise SystemExit(0 if OUTPUT.exists() and OUTPUT.read_text() == expected else 1)
    OUTPUT.write_text(expected)
